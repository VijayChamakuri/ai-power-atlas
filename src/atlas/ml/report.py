"""Writes every BA and site, including failures, so the gate decision sees the whole result."""

import pandas as pd

from atlas.ml.detectability import BaResult


def _number(value: float | None, digits: int = 0) -> str:
    return "" if value is None or pd.isna(value) else f"{value:,.{digits}f}"


def render_results(
    results: dict[str, BaResult],
    candidates: pd.DataFrame,
    table: pd.DataFrame,
    sites: pd.DataFrame,
    seed: pd.DataFrame,
    commit: str,
    rule_verdict: str,
) -> str:
    peaks = candidates.set_index("ba")["peak_mw"].to_dict()
    lines = [
        "# M1 detectability results",
        "",
        f"Generated by `atlas analyze detectability` at commit `{commit[:7]}`, on the data frozen",
        "at 2026-10-31. Method: [docs/analysis_plan.md](analysis_plan.md).",
        "",
        f"The plan's rule says: **{rule_verdict}**. Vijay makes the decision in ADR-0002.",
        "",
        "## Minimum detectable step per BA",
        "",
        "`Rate at 0` should be near 5% and `Rate at MDE` near 80%. `Injected` adds the step to",
        "real demand and re-measures. Pseudo-dates overlap heavily, so each MDE is rough.",
        "",
        "| BA | Status | Pseudo-dates | Peak MW | MDE MW | MDE % of peak | Rate at 0 | Rate at MDE "
        "| Injected | Dropped hours |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for ba, result in results.items():
        peak = peaks.get(ba)
        percent = result.mde_mw / peak * 100 if result.mde_mw is not None and peak else None
        lines.append(
            f"| {ba} | {result.status} | {result.dates} | {_number(peak)} "
            f"| {_number(result.mde_mw)} | {_number(percent, 1)} "
            f"| {_number(result.rate_at_zero, 2)} | {_number(result.rate_at_mde, 2)} "
            f"| {_number(result.injected_rate, 2)} | {result.dropped_hours} |"
        )
    lines += [
        "",
        "AEP is the secondary analysis. It uses PJM's weather counties, and it cannot alone turn a",
        "no-go into a go.",
        "",
        "## Sites against their BA's MDE",
        "",
        "`Eligible` means no on-site power flag, one BA polygon, and a BA with an MDE. `Implied",
        "utilization` is how hard a site would have to run to be seen.",
        "",
        "| Site | BA | Power MW | First date | MDE MW | Implied utilization | Flag | Overlap "
        "| Eligible | Passes go |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in table[table["mde_mw"].notna()].to_dict("records"):
        lines.append(
            f"| {row['site']} | {row['ba']} | {_number(row['power_mw'])} | {row['first_date']} "
            f"| {_number(row['mde_mw'])} | {_number(row['implied_utilization'], 2)} "
            f"| {'yes' if row['behind_meter_risk'] else ''} | {'yes' if row['overlap'] else ''} "
            f"| {'yes' if row['eligible'] else ''} | {'yes' if row['passes_go'] else ''} |"
        )
    aep = results.get("AEP")
    if aep is not None and aep.mde_mw is not None:
        lines += ["", "## Secondary: sites against the AEP zone's MDE", ""]
        lines += ["| Site | Power MW | Implied utilization | Flag |", "|---|---|---|---|"]
        for row in sites[sites["site"].isin(seed["site"])].to_dict("records"):
            utilization = aep.mde_mw / row["power_mw"]
            flag = "yes" if row["behind_meter_risk"] else ""
            lines.append(
                f"| {row['site']} | {_number(row['power_mw'])} | {utilization:.2f} | {flag} |"
            )
    lines += [
        "",
        "## Baseline against benchmarks",
        "",
        "Newest out-of-sample window per BA, up to 545 days ahead. EIA's forecast and seasonal",
        "naive see far fresher data, so this model should lose: its job is weather normalization.",
        "",
        "| BA | Model MAPE | Naive MAPE | EIA MAPE | Model RMSE | Naive RMSE | EIA RMSE "
        "| Model peak MAE | Naive peak MAE | EIA peak MAE |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for ba, result in results.items():
        if not result.scores:
            continue
        model, naive, eia = (
            result.scores["model"],
            result.scores["seasonal_naive"],
            result.scores["eia_day_ahead"],
        )
        lines.append(
            f"| {ba} | {model['mape']:.1f} | {naive['mape']:.1f} | {eia['mape']:.1f} "
            f"| {model['rmse']:,.0f} | {naive['rmse']:,.0f} | {eia['rmse']:,.0f} "
            f"| {model['peak_hour_mae']:,.0f} | {naive['peak_hour_mae']:,.0f} "
            f"| {eia['peak_hour_mae']:,.0f} |"
        )
    return "\n".join(lines) + "\n"
